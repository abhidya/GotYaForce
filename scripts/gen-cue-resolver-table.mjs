#!/usr/bin/env node
// Dumps the GG4E sound-cue resolution data from boot.dol into a TypeScript constants
// module consumed by packages/audio/src/cueResolver.ts.
//
// Resolution mechanism (ROM-faithful 1:1, NOT a hand-tuned map):
//   zz_00f036c_(actor, cueId)                          @ chunk_0026.c:792 (0x800f036c)
//     └─ actor==0 → zz_00efb3c_(cueId, 0, 0x7f, 0x40, 0x2000)
//        └─ actor!=0 → zz_00f04b4_(cueId, actorPos, actor+0x96)  (position-panned; same
//                     soundId decomposition, ends in the same zz_00efb3c_ call)
//   zz_00efb3c_(soundId, ...)                          @ chunk_0026.c:435 (0x800efb3c)
//     └─ guard: (int)soundId < 0x180                   ← CUE_MAX_SOUND_ID
//     └─ bank   = soundId >> 7                          ← CUE_BANK_SHIFT
//     └─ sample = soundId & 0x7f                        ← CUE_SAMPLE_MASK
//     └─ zz_00f0f84_(bank, sample, ...) routes via DAT_802d0bec[bank] = {tsb,chd,dpk}
//
// There is NO DOL-resident cue→sound lookup TABLE: the cue id passed to playSound IS the
// soundId, decomposed arithmetically. The only DOL-resident table in this path is the
// bank-routing table DAT_802d0bec, dumped below. The manifest idScheme (se_<soundId 3-hex>)
// is the asset-side key this resolver emits.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const BOOT_DOL_PATH = "user-data/GG4E/disc/sys/boot.dol";
const OUT_PATH = "packages/audio/src/cueResolverTable.generated.ts";

const ADDRS = {
  // DAT_802d0bec: 4 banks × 3 big-endian u16 (tsb/chd/dpk AFS member indices). Indexed as
  // `short*` (stride 3) at chunk_0005.c:706 inside zz_0043390_'s bank-attach loop:
  // param_9==0 walks banks 0..2 (battle soundbanks), param_9!=0 walks bank 3 (menu bank).
  bankTable: 0x802d0bec,
};

const BANK_COUNT = 4; // banks 0,1,2 (battle/title) + bank 3 (menu); see zz_0043390_.
// soundbank names are NOT in the DOL — they are the AFS member labels (proven by
// PORT-1TO1-STATUS.md:1148-1151). Attached here only as a derived annotation.
const BANK_NAMES = ["snd_com01", "snd_com02", "snd_com03", "snd_com04"];

function hex(value, width = 8) {
  return `0x${value.toString(16).padStart(width, "0")}`;
}

function runtimeToFileOffset(dol, addr) {
  for (let index = 0; index < 18; index += 1) {
    const fileOffset = dol.readUInt32BE(index * 4);
    const runtimeAddress = dol.readUInt32BE(0x48 + index * 4);
    const size = dol.readUInt32BE(0x90 + index * 4);
    if (size > 0 && addr >= runtimeAddress && addr < runtimeAddress + size) {
      return fileOffset + (addr - runtimeAddress);
    }
  }
  throw new Error(`DOL address ${hex(addr)} is outside mapped sections`);
}

function readAt(dol, addr, len) {
  const off = runtimeToFileOffset(dol, addr);
  return dol.subarray(off, off + len);
}

function readU16(buf, off) {
  return buf.readUInt16BE(off);
}

const dol = readFileSync(BOOT_DOL_PATH);
const bootDolSha1 = createHash("sha1").update(dol).digest("hex");

const bankBuf = readAt(dol, ADDRS.bankTable, BANK_COUNT * 6);
const bankTable = Array.from({ length: BANK_COUNT }, (_, bank) => ({
  bank,
  soundbank: BANK_NAMES[bank],
  tsb: readU16(bankBuf, bank * 6),
  chd: readU16(bankBuf, bank * 6 + 2),
  dpk: readU16(bankBuf, bank * 6 + 4),
}));

const source = {
  bootDolPath: BOOT_DOL_PATH,
  bootDolSha1,
  evidence:
    "zz_00f036c_ (chunk_0026.c:792) forwards cueId verbatim to zz_00efb3c_ (chunk_0026.c:435), which guards (int)soundId<0x180 and decomposes bank=soundId>>7, sample=soundId&0x7f, then routes via DAT_802d0bec[bank]={tsb,chd,dpk} (chunk_0005.c:706). No cue→sound table exists; the cue IS the soundId.",
  addresses: { bankTable: hex(ADDRS.bankTable) },
  generatedBy: path.basename(import.meta.url),
};

const out = `// Generated by scripts/gen-cue-resolver-table.mjs from user-data/GG4E/disc/sys/boot.dol.
// Do not hand-edit; rerun the generator after updating DOL/decomp evidence.
//
// Resolution mechanism (ROM-faithful 1:1): the cue id passed to playSound IS the soundId.
// zz_00efb3c_ (chunk_0026.c:435) guards soundId<0x180 and splits bank=soundId>>7,
// sample=soundId&0x7f, routed through DAT_802d0bec[bank] (the table below). There is no
// cue→sound lookup table in the DOL — only this bank-routing table.

export const CUE_RESOLVER_SOURCE = ${JSON.stringify(source, null, 2)} as const;

// DAT_802d0bec — 4 banks × 3 big-endian u16 (tsb/chd/dpk AFS member indices). Read as
// short* (stride 3) at chunk_0005.c:706: banks 0..2 = battle/title, bank 3 = menu.
export const CUE_BANK_TABLE = ${JSON.stringify(bankTable, null, 2)} as const;

// zz_00efb3c_ guard immediate (chunk_0026.c:440): soundIds >= 0x180 are silently dropped.
// 0x180>>7 == 3, so exactly banks 0,1,2 are reachable via playSound; bank 3 (menu) is
// only attached via the param_9!=0 branch of zz_0043390_ and never dispatched by playSound.
export const CUE_MAX_SOUND_ID = 0x180 as const;
export const CUE_BANK_SHIFT = 7 as const;
export const CUE_SAMPLE_MASK = 0x7f as const;
export const CUE_BATTLE_BANK_COUNT = 3 as const;
`;

writeFileSync(OUT_PATH, out);
console.log(`wrote ${OUT_PATH} (bank table: ${bankTable.map((b) => `${b.soundbank}{${b.tsb},${b.chd},${b.dpk}}`).join(", ")})`);
