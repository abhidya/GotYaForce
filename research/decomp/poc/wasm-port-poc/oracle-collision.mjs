      actionIndex: 0,
      hitRecord: {
        hpDamage: 40,
        scalingWord: 0,
        priorityByte: 0,
        gaugeByte: 0,
        reactionBits: 0,
        knockbackStrength: 4,
        knockbackMode: 1,
        reactionAnimVariant: 0,
        flagsA: 0,
        flagsB: 0
      },
      descriptorFlags: 0,
      shapeType: 2,
      pos98: { x: 0, y: 0, z: 0 },
      pos64: { x: 0, y: 0, z: 0 }
