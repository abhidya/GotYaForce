var DATA = damageFormula_default;
var HANDICAP_NEUTRAL_BYTE = 3;
function borgNumberToBorgId(borgNumber) {
  const family = borgNumber >>> 8 & 255;
  const variant = borgNumber & 255;
  return "pl" + family.toString(16).padStart(2, "0") + variant.toString(16).padStart(2, "0");
}
function lookupTypeCategory(borgNumber) {
  const family = borgNumber >>> 8 & 255;
  const variant = borgNumber & 255;
  const row = TYPE_CATEGORY_REMAP[family];
  return row != null && variant >= 0 && variant < row.length ? row[variant] ?? 0 : 0;
}
function typeMultiplier(attackerBorgNumber, defenderBorgNumber) {
  const attackerCategory = lookupTypeCategory(attackerBorgNumber);
  const defenderCategory = lookupTypeCategory(defenderBorgNumber);
  return TYPE_MULTIPLIER_MATRIX[defenderCategory]?.[attackerCategory] ?? 1;
}
function forceGaugeRatioIndex(energy, energyMax) {
  if (!energyMax || energyMax <= 0) return 0;
  return clampIndex(32 - Math.trunc(Math.max(0, energy) * 32 / energyMax), 32);
}
function computeBaseDamage(attacker, defender, basePower, ctx) {
  if (!(basePower > 0)) return 0;
  if (ctx.victimStatusImmune) return 0;
  const hero = attacker.heroFlag !== 0 ? 1 : 0;
  let acc = basePower * sourcePowerMultiplier(attacker.power);
  if (attacker.isBorg && attacker.isActive) {
    if (attacker.pairAttack !== 0) acc *= DATA.scalars.pairNerf_80436f9c;
    acc *= flatValue(DATA.attackRankBySideRank_804335e0, hero, attacker.sideRank);
    if (ctx.cpuHalvingEnabled && attacker.heroFlag !== 0 && attacker.team === 0) acc *= DATA.scalars.half_80436f7c;
    if (attacker.hp < 201) {
      acc *= curveValue(
        DATA.attackerHpCurves_804335e8,
        hero,
        ctx.attackerHpCurveIndex,
        hpRatioIndex(attacker.hp, attacker.maxHp)
      );
    }
    acc *= curveValue(
      DATA.attackerForceCurves_804335f0,
      hero,
      ctx.attackerForceCurveIndex,
      clampIndex(attacker.forceRatioIndex, 32)
    );
    acc *= flatValue(DATA.attackHandicap_804335f8, hero, attacker.handicap);
    if (defender.isBorg && defender.isActive) {
      acc *= typeMultiplier(attacker.borgNumber, defender.borgNumber);
    }
  }
  let dmg = acc;
  if (defender.isBorg && defender.isActive) {
    const defHero = defender.heroFlag !== 0 ? 1 : 0;
    let f = dmg;
    if (defender.pairAttack !== 0) f *= DATA.scalars.half_80436f7c;
    const selectors = ctx.defenderDefenseCurveSelectors ?? DATA.defenseCurveSelectors_pldata_9c9d9e[borgNumberToBorgId(defender.borgNumber)] ?? [0, 0, 0];
    f *= curveValue(DATA.defenseRankCurves_80433600, defHero, selectors[0], defender.sideRank);
    if (ctx.cpuHalvingEnabled && defender.heroFlag !== 0 && defender.team === 0) f *= DATA.scalars.half_80436f7c;
    f *= 1 / sourcePowerMultiplier(defender.power);
    const postHitHp = Math.max(0, defender.hp - basePower);
    if (postHitHp < 201) {
      f *= curveValue(
        DATA.defenderHpCurves_80433608,
        defHero,
        selectors[1],
        hpRatioIndex(postHitHp, defender.maxHp)
      );
    }
    f *= curveValue(
      DATA.defenderForceCurves_80433610,
      defHero,
      selectors[2],
      clampIndex(defender.forceRatioIndex, 32)
    );
    f *= flatValue(DATA.defenseHandicap_80433618, defHero, defender.handicap);
    if ((ctx.flagsB & 16384) === 0) {
      f *= DATA.comboRankScale_802c7ca0[clampIndex(defender.comboRank, DATA.comboRankScale_802c7ca0.length)] ?? 1;
    }
    if (ctx.victimSpawnProtection) f *= DATA.scalars.half_80436f7c;
    dmg = f;
  }
  if (attacker.team === defender.team && (ctx.flagsA & 4096) === 0) {
    dmg *= DATA.scalars.sameTeam_80437024;
  }
  if ((ctx.flagsA & 4096) !== 0 && ((ctx.victimResistanceMask ?? 0) & 4096) !== 0) {
    dmg /= DATA.scalars.blockDiv_80437028;
  }
  if (dmg < 1) dmg = 1;
  return Math.trunc(dmg);
}
function sourcePowerMultiplier(power) {
  return 1 + 0.5 * (power - 1);
}
function hpRatioIndex(currentHp, maxHp) {
  const denom = Math.min(Math.max(1, maxHp), 200);
  const clampedCurrent = Math.max(0, currentHp);
  return clampIndex(32 - Math.trunc(clampedCurrent * 32 / denom), 32);
}
function curveValue(sets, hero, selector, index) {
  const curves = sets[hero]?.curves;
  const curve = curves?.[clampIndex(selector, curves.length)];
  return curve?.[clampIndex(index, curve.length)] ?? 1;
}
function flatValue(sets, hero, index) {
  const values = sets[hero]?.values;
  return values?.[clampIndex(index, values.length)] ?? 1;
}
function clampIndex(value, length) {
  if (length <= 0) return 0;
  return Math.max(0, Math.min(length - 1, Math.trunc(value)));
}
function applyHpDamage(target, amount) {
  if (target.hp === 0) return;
  target.prevHp = target.hp;
  let hp = target.hp - amount;
  if (hp < 0) hp = 0;
  else if (target.maxHp < hp) hp = target.maxHp;
  target.hp = hp;
}
function defaultSourceDamageActor(borgNumber, maxHp = 200) {
  return {
    borgNumber,
    team: 0,
    heroFlag: 0,
    pairAttack: 0,
    power: 1,
    hp: maxHp,
    maxHp,
    handicap: HANDICAP_NEUTRAL_BYTE,
    comboRank: 0,
    forceRatioIndex: 0,
    sideRank: 0,
    isBorg: true,
    isActive: true
  };
}
function defaultSourceDamageContext() {
  return {
    flagsA: 0,
    flagsB: 0,
    attackerHpCurveIndex: 0,
    attackerForceCurveIndex: 0
  };
}
function runSourceDamageSelfTests(assert) {
  assert(lookupTypeCategory(2816) === 15, "lookupTypeCategory(0x0b00/pl0b00) === 15");
  assert(lookupTypeCategory(1793) === 12, "lookupTypeCategory(0x0701/pl0701) === 12");
  assert(lookupTypeCategory(1557) === 4, "lookupTypeCategory(0x0615/pl0615 G RED) === 4");
  assert(borgNumberToBorgId(1557) === "pl0615", "borgNumberToBorgId(0x0615) === pl0615");
  assert(typeMultiplier(2816, 1793) === 1.25, "typeMultiplier pl0b00->pl0701 === 1.25 (SE)");
  assert(typeMultiplier(1793, 2816) === 0.75, "typeMultiplier pl0701->pl0b00 === 0.75 (NVE)");
  assert(typeMultiplier(0, 0) === 1, "typeMultiplier same-cat neutral === 1.0");
  assert(TYPE_MULTIPLIER_MATRIX[12][15] === 1.25, "matrix[12][15] === 1.25 (defender-row/attacker-col)");
  assert(TYPE_MULTIPLIER_MATRIX[15][12] === 0.75, "matrix[15][12] === 0.75");
  assert(TYPE_MULTIPLIER_MATRIX[0][0] === 1, "matrix[0][0] === 1.0");
  const neutralCtx = defaultSourceDamageContext();
  const a0 = defaultSourceDamageActor(0);
  const d0 = defaultSourceDamageActor(0, 200);
  assert(computeBaseDamage(a0, d0, 0, neutralCtx) === 0, "basePower 0 -> 0 damage");
  assert(computeBaseDamage(a0, d0, -5, neutralCtx) === 0, "basePower negative -> 0 damage");
  assert(
    computeBaseDamage(a0, d0, 1e3, { ...neutralCtx, victimStatusImmune: true }) === 0,
    "victimStatusImmune -> 0 damage"
  );
  const seAtt = defaultSourceDamageActor(2816);
  const seDef = defaultSourceDamageActor(1793);
  const nveAtt = defaultSourceDamageActor(1793);
  const nveDef = defaultSourceDamageActor(2816);
  const seDmg = computeBaseDamage(seAtt, seDef, 1e4, neutralCtx);
  const nveDmg = computeBaseDamage(nveAtt, nveDef, 1e4, neutralCtx);
  assert(seDmg > nveDmg, `SE damage (${seDmg}) > NVE damage (${nveDmg}) \u2014 type matrix wired`);
  assert(seDmg > 0 && nveDmg > 0, "both SE and NVE produce positive damage");
  const teamAtt = defaultSourceDamageActor(0);
  teamAtt.team = 0;
  const teamDefSame = defaultSourceDamageActor(0);
  teamDefSame.team = 0;
  const teamDefDiff = defaultSourceDamageActor(0);
  teamDefDiff.team = 1;
  const sameTeamDmg = computeBaseDamage(teamAtt, teamDefSame, 1e4, neutralCtx);
  const diffTeamDmg = computeBaseDamage(teamAtt, teamDefDiff, 1e4, neutralCtx);
  assert(
    sameTeamDmg <= diffTeamDmg && sameTeamDmg * 4 <= diffTeamDmg + 4,
    `same-team (${sameTeamDmg}) ~= diff-team/4 (${diffTeamDmg}) \u2014 0.25x friendly-fire`
  );
  const floored = computeBaseDamage(teamAtt, teamDefSame, 1, neutralCtx);
  assert(floored >= 1, `floored damage >= 1 (got ${floored})`);
  const weakAtt = defaultSourceDamageActor(0);
  weakAtt.power = 1;
  const strongAtt = defaultSourceDamageActor(0);
  strongAtt.power = 3;
  const neutralDef = defaultSourceDamageActor(0);
  const weakDmg = computeBaseDamage(weakAtt, neutralDef, 1e3, neutralCtx);
  const strongDmg = computeBaseDamage(strongAtt, neutralDef, 1e3, neutralCtx);
  assert(strongDmg > weakDmg, `attacker power multiplier wired (power3 ${strongDmg} > power1 ${weakDmg})`);
  const t1 = { hp: 100, maxHp: 100 };
  applyHpDamage(t1, 30);
  assert(t1.hp === 70, `applyHpDamage 100-30 -> 70 (got ${t1.hp})`);
  assert(t1.prevHp === 100, `applyHpDamage mirrors pre-HP to prevHp (got ${t1.prevHp})`);
  const t2 = { hp: 20, maxHp: 100 };
  applyHpDamage(t2, 50);
  assert(t2.hp === 0, `applyHpDamage overkill clamps at 0 (got ${t2.hp})`);
  const t3 = { hp: 90, maxHp: 100 };
  applyHpDamage(t3, -30);
  assert(t3.hp === 100, `applyHpDamage heal clamps at maxHp (got ${t3.hp})`);
  const t4 = { hp: 0, maxHp: 100 };
  applyHpDamage(t4, 50);
  assert(t4.hp === 0 && t4.prevHp === void 0, `applyHpDamage on 0-HP target is a no-op`);
}
