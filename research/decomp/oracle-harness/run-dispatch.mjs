// Uniform dispatch frame ABI v1 (OGhidra src/port_dispatch_companion.py).
const FRAME_ARG_COUNT = 0x00;
const FRAME_RET_CLASS = 0x04;
const FRAME_RET = 0x08;
const FRAME_ARGS = 0x10;
const FRAME_SLOT = 8;
const FRAME_MAX_ARGS = 16;
const CLASS_VOID = 0, CLASS_I32 = 1, CLASS_I64 = 2, CLASS_F32 = 3, CLASS_F64 = 4;
const CLASS_NAME = { 0: "void", 1: "i32", 2: "i64", 3: "f32", 4: "f64" };

