/**
 * PowerPC EABI outgoing-argument allocation, over CLASSES THE PORT DECLARED.
 * Mirrors capture_common.eabi_allocate exactly — the console side records the
 * register file raw and class-agnostically, so this is the only place the two
 * sides have to agree, and it agrees by being the same rule.
 */
function eabiAllocate(classes) {
  const out = [];
  let gpr = 3, fpr = 1, stackOff = 8;
  for (let i = 0; i < classes.length; i++) {
    const c = classes[i];
    if (c === CLASS_F32 || c === CLASS_F64) {
      if (fpr <= 8) out.push({ i, c, src: `f${fpr++}` });
      else { out.push({ i, c, src: `stack+${stackOff}` }); stackOff += 8; }
    } else if (c === CLASS_I64) {
      if (gpr % 2 === 0) gpr++;                      // aligned (odd,even) pair
      if (gpr + 1 <= 10) { out.push({ i, c, src: `r${gpr}:r${gpr + 1}` }); gpr += 2; }
      else { out.push({ i, c, src: `stack+${stackOff}` }); stackOff += 8; }
    } else {
      if (gpr <= 10) out.push({ i, c, src: `r${gpr++}` });
      else { out.push({ i, c, src: `stack+${stackOff}` }); stackOff += 4; }
    }
  }
  return out;
}

const f64FromBits = (hexBits) => {
  const b = Buffer.from(hexBits, "hex");
  return b.readDoubleBE(0);
};

/** The console's value for one allocated slot, or null when unrecorded. */
function consoleArg(spec, ev) {
  if (spec.src.startsWith("stack+")) return null;   // caller parameter area not captured
  if (spec.src.startsWith("f")) {
    const bits = ev.arg_fprs?.[spec.src];
    if (bits == null) return null;
    const d = f64FromBits(bits);
    return spec.c === CLASS_F32 ? Math.fround(d) : d;
  }
  if (spec.src.includes(":")) {
    const [hi, lo] = spec.src.split(":");
    const h = ev.arg_regs?.[hi], l = ev.arg_regs?.[lo];
    if (h == null || l == null) return null;
    return (BigInt(h >>> 0) << 32n) | BigInt(l >>> 0);
  }
  const v = ev.arg_regs?.[spec.src];
  return v == null ? null : v >>> 0;
}

async function main() {
  const captureAbs = path.resolve(capturePath);
  const { raw: captureRaw, lines } = readCaptureJsonl(captureAbs, fail);
  const header = JSON.parse(lines[0]);
  if (header.kind !== "header" || header.dispatch_schema !== DISPATCH_SCHEMA) {
    fail("capture has no valid dispatch_schema 1 header record — an unbound capture proves nothing");
  }
  if (!header.fn?.export) fail("header.fn.export is required — the capture must name the function under test");

  const cases = [];
  let endRec = null;
  for (const l of lines.slice(1)) {
    const rec = JSON.parse(l);
    if (rec.kind === "case") {
      if (endRec != null) fail("case record after the end record");
      if (rec.n !== cases.length) fail(`case records out of order: expected n=${cases.length}, got n=${rec.n}`);
      if (!Array.isArray(rec.events)) fail(`case n=${rec.n} has no events array`);
      rec.events.forEach((e, k) => {
        if (e.i !== k) fail(`case n=${rec.n} event records out of order: expected i=${k}, got i=${e.i}`);
        if (e.kind !== "call" && e.kind !== "dispatch") fail(`case n=${rec.n} event i=${k} has unknown kind ${e.kind}`);
      });
      cases.push(rec);
    } else if (rec.kind === "end") {
      if (endRec != null) fail("duplicate end record");
      endRec = rec;
    } else fail(`unknown record kind ${rec.kind}`);
  }
  if (endRec == null) fail("capture has no end record — the corpus is unbound");

  const eventTotal = cases.reduce((n, c) => n + c.events.length, 0);
  const dispatchTotal = cases.reduce(
    (n, c) => n + c.events.filter((e) => e.kind === "dispatch").length, 0);
  for (const [where, counts] of [["header", header.counts], ["end record", endRec.counts]]) {
    if (counts?.case !== cases.length) fail(`capture count mismatch: ${cases.length} case records != ${where} counts.case ${counts?.case}`);
    if (counts?.event !== eventTotal) fail(`capture count mismatch: ${eventTotal} event records != ${where} counts.event ${counts?.event}`);
    if (counts?.dispatch !== dispatchTotal) fail(`capture count mismatch: ${dispatchTotal} dispatch records != ${where} counts.dispatch ${counts?.dispatch}`);
  }

  const results = header.fn.results ?? [];
  if (results.length > 1) fail(`fn declares ${results.length} results — dispatch_schema 1 models at most one`);
  const isVoid = results.length === 0;

  // ---- non-vacuity guard 3: a case with no dispatch ----
  const vacuous = cases
    .filter((c) => !c.events.some((e) => e.kind === "dispatch"))
    .map((c) => c.n);

  const captureDir = path.dirname(captureAbs);
  const wasmPath = argOf("--wasm") ?? process.env.ORACLE_WASM ?? path.resolve(captureDir, header.wasm);
  // `--arena`, like `--wasm`, exists so a MUTANT of this capture can be
  // replayed from a scratch directory: the header's paths are relative to the
  // capture file, and a mutant does not live beside the real one.
  const arenaPath = argOf("--arena") ?? path.resolve(captureDir, header.arena);

  // ---- wrong-thunk check 2: audit the emitted table against the registry ----
  const gateEvidencePath = argOf("--gate-evidence")
    ?? path.resolve(path.dirname(wasmPath), "gate-evidence.json");
  const registryPath = argOf("--registry")
    ?? path.join(root, "research", "decomp", "data", "oracle-registry.json");
  const audit = auditTable(gateEvidencePath, registryPath);
  if (audit.status === "fail") {
    console.log(`DISPATCH TABLE AUDIT: ${audit.report}`);
  }

  // ---- shims ----
  const state = {
    caseIdx: 0, evIdx: 0, events: [], nested: 0, nestedUnobserved: 0,
    targetsCompared: 0, argsCompared: 0, retsCompared: 0,
    resolvedTargets: new Set(), dispatchOwnedBytes: 0, bridgedReplayedBytes: 0, nestedReplayedBytes: 0,
    caseReplayedBytes: 0,
    // A STACK, not a slot: an in-table dispatch runs the port's own ROM code,
    // which may itself dispatch. A single `pending` would lose the outer call
    // and the outer `exit` would then never advance the event index.
    stack: [],
  };
  let shimMem = null;
  const readFrame = (argptr) => {
    const dv = shimMem.dv;
    const n = Math.min(dv.getUint32(argptr + FRAME_ARG_COUNT, true), FRAME_MAX_ARGS);
    return { n, argptr, dv };
  };
  const readClasses = (classptr, n) => {
    const out = [];
    for (let k = 0; k < n; k++) out.push(shimMem.u8[classptr + k]);
    return out;
  };
  const slotBase = (argptr, k) => argptr + FRAME_ARGS + k * FRAME_SLOT;
  const readSlot = (dv, base, cls) => {
    switch (cls) {
      case CLASS_I32: return dv.getUint32(base, true) >>> 0;
      case CLASS_I64: return dv.getBigInt64(base, true) & 0xffffffffffffffffn;
      case CLASS_F32: return dv.getFloat32(base, true);
      case CLASS_F64: return dv.getFloat64(base, true);
      default: return null;
    }
  };

  const expectEvent = (wantKind, describe) => {
    if (state.evIdx >= state.events.length) {
      throw new ExtraEvent({
        n: state.caseIdx, i: state.evIdx, kind: "extra_event",
        report: `extra event in case n=${state.caseIdx} at i=${state.evIdx}: ` +
          `capture ends after ${state.events.length} events, port did ${describe}`,
      });
    }
    const rec = state.events[state.evIdx];
    if (rec.kind !== wantKind) {
      throw new DispatchMismatch({
        n: state.caseIdx, i: state.evIdx, kind: "event_kind",
        report: `event-kind divergence in case n=${state.caseIdx} at i=${state.evIdx}: ` +
          `expected a ${rec.kind}, port did ${describe}`,
      });
    }
    return rec;
  };

  const onDispatchEnter = (site, gcAddr, argptr, classptr, resolved) => {
    if (state.nested > 0) {
      // A dispatch made from INSIDE an in-table dispatched callee. That callee's
      // internals are outside this claim; count it and let it run.
      state.nestedUnobserved++;
      state.stack.push({ nested: true, argptr, resolved });
      if (resolved) state.nested++;
      return;
    }
    const rec = expectEvent("dispatch", `dispatch to ${hex(gcAddr)}`);
    const want = parseAddr(rec.resolved_target) >>> 0;
    const got = gcAddr >>> 0;
    if (want !== got) {
      throw new DispatchMismatch({
        n: state.caseIdx, i: state.evIdx, kind: "target",
        report: `DISPATCH TARGET divergence in case n=${state.caseIdx} at i=${state.evIdx}` +
          `${rec.site ? ` (site ${rec.site})` : ""}: the console's ${rec.branch ?? "bctrl"} at ` +
          `${rec.at} jumped to ${hex(want)}${rec.resolved_name ? ` (${rec.resolved_name})` : ""}, ` +
          `the port dispatched to ${hex(got)}`,
      });
    }
    state.targetsCompared++;
    state.resolvedTargets.add(hex(want));

    // ---- wrong-thunk check 3: resolution class must match the audited table
    const inTable = audit.addresses.has(hex(want));
    if (audit.status !== "absent" && !!resolved !== inTable) {
      throw new DispatchMismatch({
        n: state.caseIdx, i: state.evIdx, kind: "resolution_class",
        report: `resolution-class divergence in case n=${state.caseIdx} at i=${state.evIdx}: ` +
          `the module reported ${resolved ? "IN-TABLE" : "BRIDGED"} for ${hex(want)} but the ` +
          `emitted dispatch table ${inTable ? "contains" : "does not contain"} that address`,
      });
    }

    // ---- arguments: allocate from the classes the PORT declared ----
    const { n, dv } = readFrame(argptr);
    const classes = readClasses(classptr, n);
    const alloc = eabiAllocate(classes);
    for (const spec of alloc) {
      const expected = consoleArg(spec, rec);
      if (expected == null) continue;                 // stack area: not captured
      const actual = readSlot(dv, slotBase(argptr, spec.i), spec.c);
      const same = typeof expected === "bigint"
        ? BigInt.asUintN(64, expected) === BigInt.asUintN(64, actual)
        : Object.is(expected, actual)
          || (typeof expected === "number" && typeof actual === "number"
              && expected === actual);
      if (!same) {
        throw new DispatchMismatch({
          n: state.caseIdx, i: state.evIdx, kind: "args",
          report: `dispatch-argument divergence in case n=${state.caseIdx} at i=${state.evIdx} ` +
            `-> ${hex(got)}: slot ${spec.i} (class ${CLASS_NAME[spec.c]}, console ${spec.src}) ` +
            `expected ${fmtVal(expected)}, port marshalled ${fmtVal(actual)}`,
        });
      }
      state.argsCompared++;
    }
    state.stack.push({ nested: false, rec, argptr, resolved, classes,
                       nestedAtEntry: state.nestedUnobserved });
    if (resolved) state.nested++;
  };

  const onDispatchExit = (site, gcAddr, argptr, resolved, result) => {
    const p = state.stack.pop();
    if (p == null) return;
    if (resolved) state.nested = Math.max(0, state.nested - 1);
    if (p.nested) return;
    const rec = p.rec;
    // A BRIDGED return was supplied by this harness — comparing it would be
    // comparing our own input. Only an in-table resolution produced a value.
    if (resolved && rec.ret_regs) {
      const dv = shimMem.dv;
      const cls = dv.getUint32(argptr + FRAME_RET_CLASS, true);
      const base = argptr + FRAME_RET;
      let expected = null, actual = null;
      if (cls === CLASS_I32) { expected = rec.ret_regs.r3 >>> 0; actual = dv.getUint32(base, true) >>> 0; }
      else if (cls === CLASS_I64) {
        expected = (BigInt(rec.ret_regs.r3 >>> 0) << 32n) | BigInt(rec.ret_regs.r4 >>> 0);
        actual = BigInt.asUintN(64, dv.getBigInt64(base, true));
      } else if (cls === CLASS_F32) { expected = Math.fround(f64FromBits(rec.ret_regs.f1)); actual = dv.getFloat32(base, true); }
      else if (cls === CLASS_F64) { expected = f64FromBits(rec.ret_regs.f1); actual = dv.getFloat64(base, true); }
      if (expected != null) {
        const same = typeof expected === "bigint" ? expected === actual : Object.is(expected, actual);
        if (!same) {
          throw new DispatchMismatch({
            n: state.caseIdx, i: state.evIdx, kind: "dispatch_ret",
            report: `dispatch-return divergence in case n=${state.caseIdx} at i=${state.evIdx} ` +
              `-> ${hex(gcAddr)}: expected ${fmtVal(expected)}, got ${fmtVal(actual)} ` +
              `(class ${CLASS_NAME[cls] ?? cls})`,
          });
        }
        state.retsCompared++;
      }
    }
    // ---- the watch window across the dispatch --------------------------
    // A BRIDGED dispatch is a stub: the console's side effects must be
    // REPLAYED into the arena or the rest of the case runs on state the port
    // never produced. An IN-TABLE dispatch is the port's OWN code: replaying
    // the console's bytes over it would erase exactly the evidence, and would
    // make the case's `owned_end` comparison vacuous. So one is applied and
    // the other is COMPARED, and the artifact counts them separately.
    // An in-table dispatch's writes are the PORT'S OWN only if nothing inside
    // it was serviced by this harness. The moment a nested call or a nested
    // dispatch had to be stubbed, the callee ran on values the harness supplied
    // (or on a table entry the capture never seeded), and its watch-window
    // bytes are no longer a statement about the port. Comparing them then
    // would be a FALSE RED; replaying them is what the boundary convention
    // already does for every other stub. Which of the two happened is counted
    // separately in the artifact, so the weakening can never be invisible.
    const clean = p.resolved && (state.nestedUnobserved === p.nestedAtEntry);
    if (clean) {
      const bad = firstOwnedMismatch(shimMem.u8, rec.deltas, fail);
      if (bad != null) {
        throw new DispatchMismatch({
          n: state.caseIdx, i: state.evIdx, kind: "dispatch_owned_write",
          report: `owned-write divergence in case n=${state.caseIdx} after the in-table ` +
            `dispatch at i=${state.evIdx} -> ${hex(gcAddr)}: addr ${hex(bad.addr)} ` +
            `expected ${fmtByte(bad.expected)} got ${fmtByte(bad.got)}`,
        });
      }
      for (const d of rec.deltas ?? []) {
        state.dispatchOwnedBytes += Buffer.from(d.b64, "base64").length;
      }
    } else {
      applyDeltasIfAny(rec);
      for (const d of rec.deltas ?? []) {
        const len = Buffer.from(d.b64, "base64").length;
        if (p.resolved) state.nestedReplayedBytes += len;
        else state.bridgedReplayedBytes += len;
        state.caseReplayedBytes += len;
      }
    }
    state.evIdx++;
  };

  const applyDeltasIfAny = (rec) => {
    for (const d of rec?.deltas ?? []) {
      const b = Buffer.from(d.b64, "base64");
      shimMem.u8.set(b, parseAddr(d.addr));
    }
  };

  const onMiss = (gcAddr, argptr) => {
    const p = state.stack[state.stack.length - 1];
    if (p == null || p.nested) return 0;
    // Supply the console's r3 word, declared as i32. This is an INPUT to the
    // port, itemised in the artifact, never a verified result.
    const r3 = (p.rec?.ret_regs?.r3 ?? 0) >>> 0;
    shimMem.dv.setUint32(argptr + FRAME_RET_CLASS, CLASS_I32, true);
    shimMem.dv.setBigInt64(argptr + FRAME_RET, 0n, true);
    shimMem.dv.setUint32(argptr + FRAME_RET, r3, true);
    return r3 | 0;
  };

  const onDirectCall = (name, actualArgs) => {
    if (state.nested > 0) { state.nestedUnobserved++; return 0; }
    const rec = expectEvent("call", `call ${name}${fmtArgs(actualArgs)}`);
    if (name !== rec.callee) {
      throw new DispatchMismatch({
        n: state.caseIdx, i: state.evIdx, kind: "callee",
        report: `call divergence in case n=${state.caseIdx} at i=${state.evIdx}: ` +
          `expected ${rec.callee}@${rec.callee_addr}${fmtArgs(rec.args)}, got ${name}${fmtArgs(actualArgs)}`,
      });
    }
    if (actualArgs.length !== rec.args.length || !rec.args.every((e, k) => valueEq(e, actualArgs[k]))) {
      throw new DispatchMismatch({
        n: state.caseIdx, i: state.evIdx, kind: "args",
        report: `arg divergence in case n=${state.caseIdx} at i=${state.evIdx} ${rec.callee}@${rec.callee_addr}: ` +
          `expected ${fmtArgs(rec.args)}, got ${fmtArgs(actualArgs)}`,
      });
    }
    applyDeltasIfAny(rec);
    state.evIdx++;
    if (rec.ret == null) return undefined;
    return unbox(rec.ret);
  };

  const makeShims = (ctx) => {
    shimMem = ctx;
    return new Proxy({}, {
      get: (_t, k) => {
        if (typeof k !== "string") return undefined;
        if (k === "__gf_dispatch_enter") return onDispatchEnter;
        if (k === "__gf_dispatch_exit") return onDispatchExit;
        if (k === "__gf_dispatch_miss") return onMiss;
        return (...a) => onDirectCall(k, a);
      },
    });
  };

  const { ex, wasmBytes } = await loadUnit({ wasmPath, arenaPath, makeShims });
  const memLim = importedMemoryLimits(wasmBytes);
  const memoryModel = memLim == null ? "exported" : memLim.shared ? "imported_shared" : "imported";
  const fn = ex[header.fn.export];
  if (typeof fn !== "function") fail(`wasm has no export ${header.fn.export}`);
  for (const needed of ["__gf_dispatch_at"]) {
    if (typeof ex[needed] !== "function") {
      fail(`wasm has no export ${needed} — this module was not built with the ` +
        `gate's indirect-call lowering, so its indirect calls are still ` +
        `call_indirect on the module's own table and nothing observes them`);
    }
  }

  const arena = JSON.parse(fs.readFileSync(arenaPath, "utf8"));
  const stackSave = typeof ex.emscripten_stack_get_current === "function"
    ? ex.emscripten_stack_get_current() : null;

  let divergence = null;
  let casesPassed = 0, eventsMatched = 0, retsChecked = 0, seededBytes = 0;
  let ownedBytesChecked = 0, ownedBytesAfterReplay = 0, ownedBytesMoved = 0;
  const ownedAddrsChecked = new Set();
  for (const c of cases) {
    state.caseIdx = c.n; state.evIdx = 0; state.events = c.events;
    state.nested = 0; state.stack = []; state.caseReplayedBytes = 0;
    applyArenaSegments(shimMem.u8, arena);
    // Remember what was SEEDED, address by address. An owned-region byte at
    // return that still equals the byte this harness put there is not evidence
    // about the port: it is the harness's own input read back. The two are
    // counted separately below and only the second is claimed.
    const seededAt = new Map();
    for (const s of c.seed ?? []) {
      const b = Buffer.from(s.b64, "base64");
      shimMem.u8.set(b, parseAddr(s.addr));
      seededBytes += b.length;
      seededAt.set(parseAddr(s.addr), b);
    }
    if (stackSave != null && typeof ex._emscripten_stack_restore === "function") {
      ex._emscripten_stack_restore(stackSave);
    }
    let ret;
    try {
      ret = fn(...(c.args ?? []).map(unbox));
    } catch (e) {
      if (e instanceof ExtraEvent || e instanceof DispatchMismatch) { divergence = e.detail; break; }
      divergence = { n: c.n, i: state.evIdx, kind: "trap",
        report: `case n=${c.n} trapped after ${state.evIdx} events: ${e.message}` };
      break;
    }
    if (state.evIdx !== c.events.length) {
      divergence = { n: c.n, i: state.evIdx, kind: "short",
        report: `case n=${c.n} returned after ${state.evIdx} of ${c.events.length} captured events` };
      break;
    }
    if (isVoid) {
      if (ret !== undefined) {
        divergence = { n: c.n, i: state.evIdx, kind: "ret_shape",
          report: `case n=${c.n}: capture declares a void function but the export returned ${fmtVal(ret)}` };
        break;
      }
    } else {
      if (ret === undefined) {
        divergence = { n: c.n, i: state.evIdx, kind: "ret_shape",
          report: `case n=${c.n}: capture declares result ${results[0]} but the export returned nothing` };
        break;
      }
      if (!valueEq(c.ret, ret)) {
        divergence = { n: c.n, i: state.evIdx, kind: "ret",
          report: `return divergence in case n=${c.n}: expected ${fmtVal(c.ret)}, got ${fmtVal(ret)}` };
        break;
      }
      retsChecked++;
    }
    if (c.owned_end?.length) {
      const bad = firstOwnedMismatch(shimMem.u8, c.owned_end, fail);
      if (bad != null) {
        divergence = { n: c.n, i: state.evIdx, kind: "owned_write",
          report: `owned-write divergence in case n=${c.n} at return: addr ${hex(bad.addr)} ` +
            `expected ${fmtByte(bad.expected)} got ${fmtByte(bad.got)}` };
        break;
      }
      // A watch window this case had REPLAYED into it is no longer a
      // statement about the port at return: the harness put the console's own
      // bytes there. Count those separately so the artifact can never present
      // replayed bytes as verified ones.
      for (const o of c.owned_end) {
        const expect = Buffer.from(o.b64, "base64");
        if (state.caseReplayedBytes > 0) { ownedBytesAfterReplay += expect.length; continue; }
        ownedBytesChecked += expect.length;
        ownedAddrsChecked.add(parseAddr(o.addr));
        // How many of those bytes the CASE ACTUALLY MOVED. A window the console
        // never wrote to comes back byte-identical to the seed, and comparing
        // it proves nothing at all -- it is the same vacuity the other
        // standards guard against, one level down.
        const seed = seededAt.get(parseAddr(o.addr));
        if (seed == null) { ownedBytesMoved += expect.length; continue; }
        const n = Math.min(seed.length, expect.length);
        for (let k = 0; k < n; k++) if (seed[k] !== expect[k]) ownedBytesMoved++;
        if (expect.length > n) ownedBytesMoved += expect.length - n;
      }
    }
    casesPassed++;
    eventsMatched += c.events.length;
  }

  // ---- verdict ----
  const enoughCases = cases.length >= Math.max(1, minCases);
  let verdictNote = null;
  if (!enoughCases) verdictNote = `corpus has ${cases.length} cases, below the --min-cases floor of ${minCases}`;
  else if (vacuous.length > 0) {
    verdictNote = `${vacuous.length} case(s) recorded NO dispatch — first n=${vacuous[0]}. ` +
      `A dispatch_green case that observed no dispatch cannot support the claim`;
  } else if (audit.status === "fail") {
    verdictNote = `dispatch table audit FAILED: ${audit.report}`;
  } else if (divergence == null && state.targetsCompared === 0) {
    verdictNote = "no resolved target was compared: the target comparison IS this " +
      "standard's claim, so a run that made none cannot pass";
  }
  const pass = divergence == null && enoughCases && vacuous.length === 0
    && audit.status !== "fail" && state.targetsCompared > 0;

  if (divergence != null) console.log(`DISPATCH DIVERGENCE: ${divergence.report}`);
  if (verdictNote != null) console.log(`DISPATCH VACUITY: ${verdictNote}`);
  const totalLine = `DISPATCH TOTAL cases=${casesPassed}/${cases.length} ` +
    `events=${eventsMatched}/${eventTotal} dispatches=${state.targetsCompared}/${dispatchTotal} ` +
    `targets=${state.resolvedTargets.size} args=${state.argsCompared} `;
  console.log(pass
    ? `${totalLine}DIVERGENCE: none VERDICT: DISPATCH_GREEN`
    : `${totalLine}DIVERGENCE: ${divergence ? `case ${divergence.n} event ${divergence.i}` : "none"} VERDICT: FAIL`);

  const result = {
    result_schema: 1,
    standard: STANDARD,
    unit: header.unit,
    fn: header.fn.export,
    generated_at: new Date().toISOString(),
    claim: {
      established: pass,
      summary: `the port performed the same ROM function-pointer dispatches as the console — ` +
        `same sites, same order, same RESOLVED GAMECUBE TARGETS, same frame arguments — ` +
        `on ${cases.length} recorded cases`,
      verifies: [
        `the resolved GameCube target of ${state.targetsCompared} dispatch(es), against the ` +
          `address the console's own branch register held at the branch`,
        `${state.resolvedTargets.size} distinct target address(es) reached`,
        `${state.argsCompared} argument slot(s), allocated per the PowerPC EABI from the ` +
          `value classes the port itself declared`,
        state.retsCompared > 0
          ? `${state.retsCompared} in-table dispatch return value(s)`
          : "no dispatch return value (every observed dispatch was BRIDGED, and a bridged " +
            "return is supplied by the harness, never verified)",
        state.dispatchOwnedBytes > 0
          ? `${state.dispatchOwnedBytes} watch-window byte(s) across in-table dispatches: ` +
            `the port's OWN dispatched code produced them and they are compared, not replayed`
          : "no watch-window bytes across a dispatch (every observed dispatch was bridged, " +
            "and a bridged callee's side effects are REPLAYED into the arena, never checked)",
        "the interleaving of dispatches with the function's direct out-of-unit calls",
        "the function's own return value",
        ownedBytesChecked > 0
          ? (ownedBytesMoved > 0
              ? `byte-exactness of ${ownedBytesMoved} owned-region bytes THE CASES ` +
                `ACTUALLY CHANGED, of ${ownedBytesChecked} compared at return over ` +
                `${ownedAddrsChecked.size} distinct address(es)`
              : `NOTHING about memory: all ${ownedBytesChecked} owned-region bytes ` +
                `compared at return were byte-identical to what the harness SEEDED, ` +
                `so the comparison read back its own input`)
          : ownedBytesAfterReplay > 0
            ? `NO owned-region bytes: every case had ${ownedBytesAfterReplay} byte(s) of its ` +
              `watch window REPLAYED from the console during the case, so the window at ` +
              `return is the harness's input, not the port's output`
            : "no memory bytes (no case in this corpus carried an owned-region expectation)",
        audit.status === "pass"
          ? `the emitted dispatch table: all ${audit.entries} entries agree with ` +
            `oracle-registry.json on which function lives at each GC address`
          : "the emitted dispatch table was NOT audited (no gate evidence supplied)",
      ],
      does_not_verify: [
        "any memory write set — this standard is ORTHOGONAL to oracle_green and never totals with it",
        "the CONTENTS of the ROM's function-pointer table: the capture seeds them from the " +
          "live console. What is verified is which entry the port selects",
        "a BRIDGED dispatch's return value, which this harness supplies from the console's r3 word",
        state.nestedReplayedBytes > 0
          ? `the watch window across ${state.nestedReplayedBytes} byte(s) of in-table dispatch: `
            + `those dispatches serviced nested calls from this harness, so their bytes were `
            + `REPLAYED rather than compared`
          : "no in-table dispatch had its bytes replaced for nesting",
        "a bridged callee's non-i32 return width, which the bridge does not reproduce",
        "the behaviour of any dispatched callee" +
          (state.nestedUnobserved > 0
            ? `; ${state.nestedUnobserved} call(s) made from inside an in-table target were ` +
              `serviced without comparison`
            : ""),
        "the arity of a call site, which comes from the decompiled C — the port's own substrate",
        "site identity beyond the enclosing function, for any function with more than one " +
          "indirect call (Ghidra's structured C need not order sites as the machine code does)",
        "any input outside the recorded corpus",
      ],
      orthogonal_to: ["oracle_green", "transcript_green", "boundary_green"],
      not_a_ladder: "dispatch_green observes a channel the other standards cannot see and is " +
        "blind to channels they check. It is never an upgrade of, and never totals with, any of them.",
      wrong_thunk_defence: {
        console_resolved_target: state.targetsCompared > 0,
        table_audited_against_registry: audit.status === "pass",
        resolution_class_checked: audit.status !== "absent",
        why: "a transcript taken at the thunk is self-consistent with a WRONG address-to-thunk " +
          "mapping. These three checks are each grounded outside the companion: the console's " +
          "own branch register, the DOL-derived oracle registry, and the emitted table itself.",
      },
      bounded_by_corpus: { cases: cases.length, events: eventTotal, dispatches: dispatchTotal },
    },
    harness: {
      entry: "research/decomp/oracle-harness/run-dispatch.mjs",
      git_rev: gitRevOf(root),
      sha256: sha256(fs.readFileSync(path.join(here, "run-dispatch.mjs"))),
      min_cases: minCases,
    },
    wasm: { path: wasmPath, sha256: sha256(wasmBytes), memory_model: memoryModel },
    arena: { path: relPosix(root, arenaPath), sha256: sha256(fs.readFileSync(arenaPath)) },
    capture: {
      file: relPosix(root, captureAbs), sha256: sha256(captureRaw),
      cases: cases.length, events: eventTotal, dispatches: dispatchTotal,
      source: header.source ?? null,
    },
    function: {
      export: header.fn.export, gc_addr: header.fn.gc_addr ?? null,
      params: header.fn.params ?? null, results, void: isVoid,
    },
    dispatch_sites: header.dispatch_sites ?? [],
    seeded_dispatch_tables: header.seeded_dispatch_tables ?? [],
    table_audit: audit.report_obj,
    resolved_targets: [...state.resolvedTargets].sort(),
    targets_compared: state.targetsCompared,
    arg_slots_compared: state.argsCompared,
    dispatch_returns_compared: state.retsCompared,
    nested_unobserved_calls: state.nestedUnobserved,
    owned_bytes_checked: ownedBytesChecked,
    // Of the bytes compared, how many the case actually CHANGED from what the
    // harness seeded. This is the only owned-memory figure that says anything
    // about the port; the rest is the seed read back.
    owned_bytes_moved: ownedBytesMoved,
    owned_bytes_not_counted_after_replay: ownedBytesAfterReplay,
    owned_addresses_checked: ownedAddrsChecked.size,
    seeded_bytes: seededBytes,
    dispatch_owned_bytes_compared: state.dispatchOwnedBytes,
    bridged_replayed_bytes: state.bridgedReplayedBytes,
    in_table_bytes_replayed_because_nested: state.nestedReplayedBytes,
    cases_passed: casesPassed,
    events_matched: eventsMatched,
    returns_checked: retsChecked,
    vacuous_cases: vacuous,
    divergence: divergence == null ? null
      : { n: divergence.n, i: divergence.i, kind: divergence.kind, report: divergence.report },
    verdict_note: verdictNote,
    verdict: pass ? "pass" : "fail",
  };
  const outDir = resultsDir();
  fs.mkdirSync(outDir, { recursive: true });
  const safeFn = header.fn.export.replace(/[^\w.-]/g, "_");
  fs.writeFileSync(path.join(outDir, `${header.unit}.${safeFn}.dispatch.json`),
    JSON.stringify(result, null, 1) + "\n");
  process.exitCode = pass ? 0 : 1;
}

/**
 * Wrong-thunk check 2. The companion derives each table entry's GC address
 * from chunk markers / symbol names inside the window's own sources. The
 * oracle registry is derived from the DOL. If they disagree about which
 * function lives at an address, the table is wrong and every transcript taken
 * through it is wrong in a way the transcript itself cannot show.
 */
function auditTable(gateEvidencePath, registryPath) {
  const addresses = new Set();
  if (!fs.existsSync(gateEvidencePath)) {
    return { status: "absent", addresses, entries: 0,
      report: "no gate evidence supplied", report_obj: { status: "absent", reason: `no file at ${gateEvidencePath}` } };
  }
  let evidence;
  try { evidence = JSON.parse(fs.readFileSync(gateEvidencePath, "utf8")); }
  catch (e) {
    return { status: "fail", addresses, entries: 0, report: `gate evidence unreadable: ${e.message}`,
      report_obj: { status: "fail", reason: String(e.message) } };
  }
  const table = evidence?.dispatch?.table ?? [];
  for (const row of table) addresses.add("0x" + String(row.gc_address).toLowerCase());
  if (!fs.existsSync(registryPath)) {
    return { status: "absent", addresses, entries: table.length,
      report: "no oracle registry to audit against",
      report_obj: { status: "absent", entries: table.length, reason: `no file at ${registryPath}` } };
  }
  const registry = JSON.parse(fs.readFileSync(registryPath, "utf8"));
  const byName = new Map();
  for (const f of registry.functions ?? []) byName.set(f.name, String(f.address).toLowerCase());
  const mismatches = [];
  let checked = 0;
  for (const row of table) {
    const want = byName.get(row.symbol);
    if (want == null) continue;                        // renamed / absent: not evidence
    checked++;
    const got = "0x" + String(row.gc_address).toLowerCase();
    if (want !== got) mismatches.push({ symbol: row.symbol, table: got, registry: want });
  }
  const obj = {
    status: mismatches.length ? "fail" : "pass",
    entries: table.length, cross_checked: checked,
    authority: relPosix(root, registryPath),
    mismatches,
    why: "the companion derives a thunk's GC address from the window's own sources; " +
      "the registry derives it from the DOL. A disagreement means the table routes an " +
      "address to the wrong function, which a thunk-side transcript would record faithfully.",
  };
  return {
    status: mismatches.length ? "fail" : "pass",
    addresses, entries: table.length,
    report: mismatches.length
      ? `${mismatches.length} table entry/entries contradict the registry (first: ` +
        `${mismatches[0].symbol} table=${mismatches[0].table} registry=${mismatches[0].registry})`
      : `${checked}/${table.length} entries cross-checked, all agree`,
    report_obj: obj,
  };
}
