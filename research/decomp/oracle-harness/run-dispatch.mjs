#!/usr/bin/env node
// run-dispatch.mjs — dispatch_green harness for functions that DISPATCH
// THROUGH A ROM FUNCTION-POINTER TABLE.
//
// ---------------------------------------------------------------------------
// WHY THIS STANDARD EXISTS
// ---------------------------------------------------------------------------
// 1602 of the corpus's 10954 functions (14.6 %) reach NO standard at all.
// docs/verification-status.md §3 states the reason exactly: the C is
// `(*(code *)...)()`, emcc lowers that `bctrl` to a `call_indirect` on the
// MODULE'S OWN TABLE, and no import shim can observe it — so a transcript
// would have a hole precisely where the interesting behaviour is.
// `capture_transcript.py` refuses the shape rather than producing that hole.
//
// The premise has a seam in it. The composed module's dispatch table is not
// emcc's — it is GENERATED BY THE ASSEMBLY GATE (design V4 H3): an
// address-keyed table of adapter thunks with one canonical signature, plus
// `__gf_dispatch` and the declared `__gf_dispatch_miss` host import. A thunk
// is a function the gate wrote, and a function the gate wrote can be watched.
//
// What was missing until now is the OUTBOUND half: the companion let something
// call INTO a ROM function by address, but nothing rewrote the ROM's own
// indirect call sites to go OUT through it. OGhidra `src/port_indirect_lowering.py`
// is that rewrite, and in the companion's TRACE mode each lowered site calls
// two declared imports around the dispatch. That is what this harness reads.
//
// ---------------------------------------------------------------------------
// WHAT dispatch_green CLAIMS — AND WHAT IT DOES NOT
// ---------------------------------------------------------------------------
// VERIFIED, over the N captured cases in this corpus and nothing else:
//   * the port performs exactly the captured indirect dispatches, in exactly
//     the captured order, interleaved correctly with its direct out-of-unit
//     calls;
//   * EACH DISPATCH REACHES THE SAME GAMECUBE ADDRESS THE CONSOLE'S `bctrl`
//     JUMPED TO — compared against the PC read out of CTR (or LR for `blrl`)
//     at a breakpoint on the branch itself;
//   * the arguments the port marshalled into the uniform frame equal the
//     console's argument registers, allocated per the EABI from the classes
//     THE PORT ITSELF DECLARED (so a wrong class reads a wrong register);
//   * for a dispatch that resolves INSIDE the module's own table, the value
//     the dispatch returned;
//   * the function's own return value;
//   * and, where the capture declares owned regions, those bytes at return.
//
// NOT VERIFIED:
//   * no memory write set is compared. This standard is ORTHOGONAL to
//     oracle_green and never totals with it.
//   * a BRIDGED dispatch's return is SUPPLIED by this harness from the
//     console's r3 word, so it is an input, not a result. Only in-table
//     resolutions have their return compared.
//   * the dispatched callee's own behaviour. In-table targets run the port's
//     own code and anything they do internally is outside this claim; the
//     harness counts those nested calls and reports the count.
//   * the CONTENTS of the ROM's function-pointer table, which the capture
//     seeds from the live console. What is verified is WHICH ENTRY the port
//     selects — the index computation is the behaviour under test.
//   * the arity of a call site: it comes from the decompiled C, which is the
//     port's own substrate. A mis-lifted arity is a corpus defect this
//     standard cannot see.
//   * any input outside the recorded corpus.
//
// ---------------------------------------------------------------------------
// THE WRONG-THUNK BLINDNESS, AND THE THREE THINGS THAT CLOSE IT
// ---------------------------------------------------------------------------
// A transcript taken AT the thunk cannot, by itself, tell you the thunk
// resolved to the RIGHT function: a wrong address→thunk mapping produces a
// self-consistent, wrong stream and the transcript agrees with it. This is
// the second-review finding Y2 in docs/one-to-one-completion-spec.md. Three
// independent checks close it, and the artifact records all three:
//
//   1. RESOLVED TARGET, from the console. The capture reads CTR at the branch
//      before it executes, so the console's own jump address is recorded.
//      Replay asserts the port dispatched to that address — self-consistency
//      cannot fake agreement with a second machine.
//   2. TABLE AUDIT, against an authority outside the companion. Every entry of
//      the emitted dispatch table must agree with `oracle-registry.json` on
//      what function lives at that GC address. The companion derives its
//      addresses from chunk markers and symbol names; the registry is derived
//      from the DOL. A table entry the registry contradicts fails the run
//      BEFORE any replay.
//   3. RESOLUTION-CLASS AGREEMENT. For every observed target the harness
//      checks that `resolved` (in-table vs bridged) matches whether the table
//      actually contains that address, so a table that quietly grew or lost an
//      entry cannot pass unnoticed.
//
// ---------------------------------------------------------------------------
// NON-VACUITY GUARDS
// ---------------------------------------------------------------------------
//   1. zero cases can never pass;
//   2. fewer than --min-cases cases can never pass;
//   3. a case with NO dispatch event is vacuous FOR THIS STANDARD and fails
//      the run — a dispatch_green result that observed no dispatch would be
//      exactly the emptiness the standard exists to remove;
//   4. a run in which no resolved target was ever compared cannot pass, even
//      if every case matched, because the target comparison IS the claim.
//
// Verdict token: DISPATCH_GREEN. Artifact: <unit>.<export>.dispatch.json.
// Neither string is shared with run-unit.mjs (VERDICT: PASS / <unit>.json),
// run-spine.mjs (BOUNDARY_GREEN / .boundary.json) or run-transcript.mjs
// (TRANSCRIPT_GREEN / .transcript.json).
//
// Usage:
//   node run-dispatch.mjs --capture <file.jsonl> [--wasm <path>] [--arena <path>]
//        [--gate-evidence <gate-evidence.json>] [--registry <oracle-registry.json>]
//        [--min-cases N]
