class SyntheticTests(unittest.TestCase):
    def test_inventory_fixed_order_widths_bits_and_independent_inverse(self):
        self.assertEqual(a.CELLS, CELLS)
        self.assertEqual(a.DATA5_MAPPING, MAPPING)
        self.assertEqual(sum(row[2] for row in CELLS), 16)
        self.assertEqual(set(PAYLOADS), {0x804379d8, 0x804379ac, 0x804379a8})
        for row, value, read in zip(CELLS, VALUES, READS):
            label, address, width, kind, bits, digest = row
            raw = PAYLOADS[address]
            self.assertEqual(len(raw), width)
            self.assertEqual(int.from_bytes(raw, 'big'), bits)
            self.assertEqual(hashlib.sha256(raw).hexdigest(), digest)
            db = FakeDB(raw)
            result = a.cell_evidence(db, MAPPING, address, width)
            self.assertEqual(db.calls, [read])
            self.assertEqual(result['value'], value)
            self.assertEqual(result['bits'], f'{bits:0{width * 2}x}')
            self.assertEqual(result['type'], kind)
            self.assertEqual(result['label'], label)
            self.assertEqual(result['sha256'], digest)
            self.assertEqual(struct.pack('>f' if kind == 'f32' else '>d', result['value']), raw)
        self.assertEqual(math.copysign(1, VALUES[2]), 1)
        self.assertEqual(struct.pack('>f', -VALUES[2]), bytes.fromhex('80000000'))

    def test_all_128_selected_payload_bit_mutations_refuse(self):
        count = 0
        for _, address, width, _, _, _ in CELLS:
            raw = PAYLOADS[address]
            for byte in range(width):
                for bit in range(8):
                    changed = raw[:byte] + bytes([raw[byte] ^ 1 << bit]) + raw[byte+1:]
                    with self.assertRaisesRegex(a.c.FormatError, 'digest mismatch'):
                        a.cell_evidence(FakeDB(changed), MAPPING, address, width)
                    count += 1
        self.assertEqual(count, 128)

