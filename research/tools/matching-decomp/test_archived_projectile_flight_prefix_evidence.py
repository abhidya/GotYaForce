    def test_full_signed_short_conversion_domain_independent_inverse(self):
        # This tests only exact integer-conversion meaning, not a runtime backend.
        for signed in range(-32768, 32768):
            encoded = (0x43300000 << 32) | ((signed & 0xffffffff) ^ 0x80000000)
            operand = struct.unpack('>d', encoded.to_bytes(8, 'big'))[0]
            self.assertEqual(operand - VALUES[0], signed)
            self.assertEqual(struct.unpack('>f', struct.pack('>f', operand - VALUES[0]))[0], signed)

    def test_nonallowlisted_addresses_widths_and_types_refuse_before_read(self):
        forbidden = (0x8007dd84, 0x8007e024, 0x8020b238, 0x802d6da0, 0x802d6db0,
                     0x804379b0, 0x804379b8, 0x804379c0, 0x804379cc, 0x804373d0)
        for _, address, width, _, _, _ in CELLS:
            for bad in (*forbidden, address - 1, address + 1, float(address), True, -1, 1 << 32):
                db = FakeDB(PAYLOADS[address])
                with self.assertRaises(a.c.FormatError): a.cell_evidence(db, MAPPING, bad, width)
                self.assertFalse(db.calls)
            for bad in (width - 1, width + 1, width + 4, float(width), True, 0, -1):
                db = FakeDB(PAYLOADS[address])
                with self.assertRaises(a.c.FormatError): a.cell_evidence(db, MAPPING, address, bad)
                self.assertFalse(db.calls)
            for index, value in enumerate(MAPPING):
                for changed in (value + 1, float(value)) if type(value) is int else ('wrong',):
                    mapping = list(MAPPING); mapping[index] = changed
                    db = FakeDB(PAYLOADS[address])
                    with self.assertRaises(a.c.FormatError): a.cell_evidence(db, tuple(mapping), address, width)
                    self.assertFalse(db.calls)
            db = FakeDB(PAYLOADS[address])
            with self.assertRaises(a.c.FormatError): a.cell_evidence(db, list(MAPPING), address, width)
            self.assertFalse(db.calls)

