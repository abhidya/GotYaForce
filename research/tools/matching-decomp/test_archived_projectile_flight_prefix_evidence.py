@unittest.skipUnless(all((SNAPSHOT_DIR / name).is_file() for name in ('db.3.gbf', 'db.4.gbf')),
                     'existing local snapshots optional; never fetched')
class ArchivedTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.reports, cls.reads, cls.auth_reads = [], [], []
        original = a.c.GBF.chain
        for name in ('db.3.gbf', 'db.4.gbf'):
            data = (SNAPSHOT_DIR / name).read_bytes(); digest = hashlib.sha256(data).hexdigest()
            reads = []
            def traced(db, *args):
                reads.append(args)
                return original(db, *args)
            with patch.object(a.c.GBF, 'chain', traced): a.c.inspect(data, digest)
            cls.auth_reads.append(reads[:]); reads.clear()
            with patch.object(a.c.GBF, 'chain', traced): cls.reports.append(a.inspect(data, digest))
            cls.reads.append(reads[:])

    def test_both_snapshots_all_facts_bits_and_values_agree(self):
        for key in ('mappings', 'cells', 'reused_initializer', 'r2_basis', 'selection_scope'):
            self.assertEqual(self.reports[0][key], self.reports[1][key])
        self.assertEqual([r['snapshot'] for r in self.reports], ['db.3.gbf', 'db.4.gbf'])
        self.assertEqual([r['snapshot_sha256'] for r in self.reports],
                         ['7b50dd2d2e17b4bfcc89a64cde27010247d0cbf0f48bd5c059f50275f40458d0',
                          '1f86813d91ea8e2c4564f96622ec42555e1dba2c78aa81ad654e892140d019f8'])
        for report in self.reports:
            self.assertEqual(report['file_bytes_table'], dict(version=0, root=-1, count=0))
            self.assertEqual([cell['value'] for cell in report['cells']], list(VALUES))
            self.assertFalse(report['reused_initializer']['read_here'])

    def test_exact_three_cell_reads_no_initializer_or_rows(self):
        for reads, auth in zip(self.reads, self.auth_reads):
            self.assertEqual(reads, auth + READS)
            self.assertTrue(all(row[0] == 263 for row in reads))
        self.assertEqual(hashlib.sha256(Path(a.c.__file__).read_bytes()).hexdigest(),
                         '24330635afc70c5364bc07b02c303206c7cf07b12f955b6c9dc7765be2276e25')

    def test_physical_spans_and_only_decoded_scalar_bits(self):
        for report in self.reports:
            for cell, read, physical in zip(report['cells'], READS, (4345790, 4345746, 4345742)):
                root, offset, width, length = read
                self.assertEqual(cell['spans'], [dict(root_buffer=root, data_buffer=264,
                    chain_offset=offset, data_offset=offset, length=width, obfuscated=True,
                    physical_offset=physical)])
                self.assertEqual(set(cell), {'label', 'address', 'end_exclusive', 'width', 'type',
                                            'bits', 'value', 'sha256', 'spans'})

    def test_real_whole_archive_and_selected_payload_tamper_refuse(self):
        data = (SNAPSHOT_DIR / 'db.3.gbf').read_bytes(); digest = hashlib.sha256(data).hexdigest()
        with patch.object(a, 'cell_evidence') as cell:
            for changed, claimed in ((data, '0' * 64), (data[:-1] + bytes([data[-1] ^ 1]), digest)):
                with self.assertRaisesRegex(a.c.FormatError, 'SHA256 not allowlisted'): a.inspect(changed, claimed)
            cell.assert_not_called()
        original = a.c.GBF.chain
        for selected in READS:
            def changed(db, *args):
                payload, spans = original(db, *args)
                if args == selected: payload = bytes([payload[0] ^ 1]) + payload[1:]
                return payload, spans
            with patch.object(a.c.GBF, 'chain', changed), self.assertRaisesRegex(a.c.FormatError, 'digest mismatch'):
                a.inspect(data, digest)

