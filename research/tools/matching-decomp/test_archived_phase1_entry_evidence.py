def encode(row, pc):
    """PPC inverse authored independently, with no reader/decoder calls."""
    n = row['mnemonic']
    if n in ('stwu', 'stw', 'stb', 'lwz', 'lbz', 'lfs', 'addi'):
        opcode, reg, imm = {'stwu': (37, 'rS', 'displacement'), 'stw': (36, 'rS', 'displacement'),
            'stb': (38, 'rS', 'displacement'), 'lwz': (32, 'rD', 'displacement'),
            'lbz': (34, 'rD', 'displacement'), 'lfs': (48, 'fD', 'displacement'),
            'addi': (14, 'rD', 'immediate')}[n]
        return opcode << 26 | row[reg] << 21 | row['rA'] << 16 | row[imm] & 65535
    if n in ('mflr', 'mtlr', 'mtctr'):
        spr, xo, reg = (8, 339, 'rD') if n == 'mflr' else (9 if n == 'mtctr' else 8, 467, 'rS')
        return 31 << 26 | row[reg] << 21 | (spr & 31) << 16 | (spr >> 5) << 11 | xo << 1
    if n in ('or', 'extsb'):
        return 31 << 26 | row['rS'] << 21 | row['rA'] << 16 | row.get('rB', 0) << 11 | (444 if n == 'or' else 954) << 1 | row['Rc']
    if n in ('bl', 'bc'):
        displacement = int(row['target'], 16) - (0 if row['AA'] else pc)
        if n == 'bl':
            return 18 << 26 | displacement & 0x3fffffc | row['AA'] << 1 | row['LK']
        return 16 << 26 | row['BO'] << 21 | row['BI'] << 16 | displacement & 0xfffc | row['AA'] << 1 | row['LK']
    if n in ('blr', 'bctrl'):
        return 19 << 26 | row['BO'] << 21 | row['BI'] << 16 | row['BH'] << 11 | (16 if n == 'blr' else 528) << 1 | row['LK']
    if n == 'cmpli':
        return 10 << 26 | row['BF'] << 23 | row['L'] << 21 | row['rA'] << 16 | row['immediate'] & 65535
    if n == 'fcmpo':
        return 63 << 26 | row['BF'] << 23 | row['fA'] << 16 | row['fB'] << 11 | 32 << 1
    raise AssertionError(n)


